const fs = require('fs');
const vm = require('vm');
const html = fs.readFileSync('static/index.html', 'utf8');
const code = html.slice(html.indexOf('function needsEvidenceReview'), html.indexOf('function collectionCard('));
const context = { files: [], console };
vm.createContext(context);
vm.runInContext(code, context);
const episode = (path, id, title, confidence = 100) => ({ path, locked: false, parsed: {}, result: { kind: 'tv', provider: 'tvmaze', provider_id: id, title, confidence } });
const local = path => ({ path, locked: false, parsed: {}, result: { kind: 'tv', confidence: 0 } });
context.files = [episode('/Media/Example Show/Season 1/a.mkv', 1, 'Example Show'), local('/Media/Example Show/Season 1/Special.mkv')];
let show = context.grouped('tv')[0];
if (show.related.length !== 1) throw Error('Expected a local related file');
context.files.push(episode('/Media/Example Show/Season 1/b.mkv', 2, 'Example Show'));
if (context.grouped('tv').some(g => g.related.length)) throw Error('Ambiguous show folder must not be assigned');
if (context.localFolders().flatMap(g => g.items).length !== 1) throw Error('Ambiguous file should remain browsable');
context.files = [local('/Media/Cartoon Collection/001 - One.mp4'), local('/Media/Cartoon Collection/002 - Two.mp4'), local('/Media/Other/001 - One.mp4')];
if (context.localCollections().length !== 1 || context.localCollections()[0].items.length !== 2) throw Error('Expected isolated numbered collection');
if (context.localFolders().flatMap(g => g.items).length !== 1) throw Error('Ungrouped file should remain browsable');
context.files = [local('/Media/Indiana Jones Collection/1981 - Raiders.mkv'), local('/Media/Indiana Jones Collection/1984 - Temple.mkv')];
if (context.localCollections().length !== 0) throw Error('Release years must not be treated as collection item numbers');
console.log('Local grouping and coverage checks passed');
